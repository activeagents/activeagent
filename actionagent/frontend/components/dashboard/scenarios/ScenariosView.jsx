import React, { useCallback, useEffect, useState } from 'react';
import { Button, Card, SegmentedControl } from '../primitives';
import ScenarioCollection from './ScenarioCollection';
import ScenarioGenerator from './ScenarioGenerator';
import ScenarioImport from './ScenarioImport';
import { Field, Notice } from './fields';
import { requestJson } from './request';
import { dashboardRelativePath, navigateTo } from '../../../utils/dashboardPath';
import { parseScenariosPath, scenariosPath } from '../../../utils/scenarios.mjs';

const TABS = [
  { value: 'collections', label: 'Collections' },
  { value: 'generate', label: 'Generate' },
  { value: 'import', label: 'Import' },
];

// /scenarios: the owner's evaluation scenarios, kept in collections (scenario
// catalogs: products, each with named sets of scenarios). Collections are
// written here entry by entry, generated by exploring a project's app in
// its sandbox's browser, or imported from YAML; any part of one exports
// back as YAML. A set runs as an evaluation of the agent under test.
//
// /scenarios/:id opens a collection, /scenarios/generate and
// /scenarios/import their tabs. The old /catalogs URLs land here.
export default function ScenariosView({ visit = 0 }) {
  const [route, setRoute] = useState(() => parseScenariosPath(dashboardRelativePath()));
  const [collections, setCollections] = useState(null);
  const [storageAvailable, setStorageAvailable] = useState(false);
  const [targets, setTargets] = useState({ agents: [], projects: [] });
  const [error, setError] = useState(null);
  const [notice, setNotice] = useState(null);
  const [creating, setCreating] = useState(false);

  useEffect(() => {
    const applyPath = () => setRoute(parseScenariosPath(dashboardRelativePath()));
    window.addEventListener('popstate', applyPath);
    window.addEventListener('dashboard:navigate', applyPath);
    return () => {
      window.removeEventListener('popstate', applyPath);
      window.removeEventListener('dashboard:navigate', applyPath);
    };
  }, []);

  const load = useCallback(async () => {
    try {
      const data = await requestJson('/api/scenario_catalogs', { fallback: 'Could not list the collections' });
      setCollections(data.catalogs || []);
      setStorageAvailable(data.storage_available === true);
      setError(null);
    } catch (e) {
      setError(e.message);
    }
  }, []);

  // Agents and projects a set runs against, and the generator explores.
  const loadTargets = useCallback(async () => {
    try {
      const [agentData, projectData] = await Promise.all([
        requestJson('/api/agents').catch(() => ({})),
        requestJson('/api/projects').catch(() => ({})),
      ]);
      setTargets({ agents: (agentData.agents || []).filter((agent) => !agent.observed), projects: projectData.projects || [] });
    } catch {
      // A convenience for the run and generate forms; the list still renders.
    }
  }, []);

  useEffect(() => {
    load();
    loadTargets();
  }, [load, loadTargets, visit]);

  const go = (next) => {
    setNotice(null);
    setError(null);
    navigateTo(scenariosPath(next));
  };

  const create = async (attributes) => {
    const data = await requestJson('/api/scenario_catalogs', { method: 'POST', body: { catalog: attributes }, fallback: 'Could not create the collection' });
    setCreating(false);
    await load();
    go({ collectionId: data.catalogs?.[0]?.id });
  };

  if (route.collectionId) {
    return (
      <ScenarioCollection
        key={route.collectionId}
        collectionId={route.collectionId}
        agents={targets.agents}
        projects={targets.projects}
        storageAvailable={storageAvailable}
        onBack={() => go({})}
        onChanged={load}
        onDeleted={async () => { await load(); go({}); }}
      />
    );
  }

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }} data-testid="scenarios-view">
      <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap' }}>
        <div>
          <h1 style={{ margin: 0, fontSize: 24, fontWeight: 700, letterSpacing: '-0.01em', color: 'var(--color-text-primary)' }}>Scenarios</h1>
          <p style={{ margin: '4px 0 0', fontSize: 14, color: 'var(--color-text-secondary)' }}>
            What your agents are evaluated on, by product and set. Write them here, generate them by exploring a project&apos;s app, or
            import and export them as YAML.
          </p>
        </div>
        {route.tab === 'collections' && (
          <Button variant="primary" onClick={() => setCreating((value) => !value)} testId="scenarios-new-collection">
            {creating ? 'Close' : 'New collection'}
          </Button>
        )}
      </div>

      <SegmentedControl options={TABS} value={route.tab} onChange={(tab) => go({ tab })} />

      {error && <Notice tone="error">{error}</Notice>}
      {notice && <Notice>{notice}</Notice>}

      {route.tab === 'generate' && (
        <ScenarioGenerator projects={targets.projects} collections={collections || []} onAccepted={load} />
      )}

      {route.tab === 'import' && (
        <ScenarioImport
          onImported={async (imported) => {
            await load();
            if (imported.length === 1) go({ collectionId: imported[0].id });
            else setNotice(`Imported ${imported.map((collection) => collection.key).join(', ') || 'nothing'}.`);
          }}
        />
      )}

      {route.tab === 'collections' && (
        <>
          {creating && <NewCollection onCreate={create} />}
          {collections === null ? (
            <p style={{ color: 'var(--color-text-secondary)' }}>Loading…</p>
          ) : collections.length === 0 ? (
            <Card testId="scenarios-empty">
              <p style={{ margin: 0, color: 'var(--color-text-secondary)' }}>
                No scenarios yet. Start a new collection, generate scenarios by exploring a project&apos;s app, or import YAML, such as the{' '}
                <code>.activeagents/evals</code> directory of a connected repository.
              </p>
            </Card>
          ) : (
            <div style={{ display: 'grid', gap: 12 }}>
              {collections.map((collection) => (
                <Card key={collection.id} style={{ cursor: 'pointer' }} onClick={() => go({ collectionId: collection.id })} testId="scenarios-collection-card">
                  <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12, flexWrap: 'wrap' }}>
                    <div>
                      <div style={{ fontWeight: 600, color: 'var(--color-text-primary)' }}>{collection.name}</div>
                      <div style={{ fontSize: 12, color: 'var(--color-text-secondary)' }}>
                        <code>{collection.key}</code>
                        {collection.source_path ? ` · ${collection.source_path}` : collection.source_kind === 'api' ? ' · written here' : ` · ${collection.source_kind}`}
                      </div>
                    </div>
                    <div style={{ fontSize: 13, color: 'var(--color-text-secondary)', textAlign: 'right' }}>
                      {collection.product_count} {collection.product_count === 1 ? 'product' : 'products'} · {collection.scenario_count} scenarios
                      <div>{collection.synced ? 'synced to storage' : storageAvailable ? 'not synced' : 'database only'}</div>
                    </div>
                  </div>
                </Card>
              ))}
            </div>
          )}
        </>
      )}
    </div>
  );
}

function NewCollection({ onCreate }) {
  const [name, setName] = useState('');
  const [key, setKey] = useState('');
  const [description, setDescription] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);

  const submit = async (event) => {
    event.preventDefault();
    setBusy(true);
    setError(null);
    try {
      await onCreate({ name: name.trim(), key: key.trim(), description: description.trim() });
    } catch (e) {
      setError(e.message);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Card testId="scenarios-new-collection-form">
      <form onSubmit={submit} style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
        <div style={{ display: 'grid', gap: 8, gridTemplateColumns: 'repeat(auto-fit, minmax(200px, 1fr))' }}>
          <Field label="Name" value={name} onChange={setName} placeholder="Support desk" />
          <Field label="Key" value={key} onChange={setKey} placeholder="made from the name when empty" mono />
        </div>
        <Field label="Description" value={description} onChange={setDescription} placeholder="optional" />
        {error && <Notice tone="error">{error}</Notice>}
        <div>
          <Button type="submit" variant="primary" disabled={busy || (!name.trim() && !key.trim())}>{busy ? 'Creating…' : 'Create collection'}</Button>
        </div>
      </form>
    </Card>
  );
}
